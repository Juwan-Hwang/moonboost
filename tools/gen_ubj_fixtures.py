"""Write ubjson_fixtures_test.mbt: the JSON fixture models re-saved by XGBoost
as UBJSON.

XGBoost loads each fixture's JSON model and saves it with
`save_raw("ubj")`; the test then checks that moonboost reads the UBJSON copy
into a model with exactly the same predictions as the JSON one.

    python tools/gen_ubj_fixtures.py
"""

import pathlib
import re

import xgboost as xgb

ROOT = pathlib.Path(__file__).resolve().parent.parent
NAMES = [
    "regression",
    "binary_logistic",
    "multi_softprob",
    "categorical",
    "dart_binary",
    "gblinear_multi",
]


def fixture_models():
    src = (ROOT / "xgboost_fixtures_test.mbt").read_text()
    models = {}
    for m in re.finditer(r"let fixture_(\w+) : Fixture = \{(.*?)\n\}", src, re.S):
        name, body = m.group(1), m.group(2)
        mm = re.search(r"model: \(\n(.*?)\n  \),", body, re.S)
        lines = [ln.strip()[2:] for ln in mm.group(1).splitlines()]
        models[name] = "".join(lines)
    return models


def main():
    models = fixture_models()
    parts = [
        f"// Generated by tools/gen_ubj_fixtures.py with xgboost {xgb.__version__}. DO NOT EDIT.\n"
    ]
    for name in NAMES:
        booster = xgb.Booster()
        booster.load_model(bytearray(models[name].encode()))
        data = bytes(booster.save_raw("ubj"))
        hx = data.hex()
        lines = [hx[i : i + 96] for i in range(0, len(hx), 96)]
        parts.append(
            f"\n///|\n/// `{name}` saved as UBJSON, in hex.\nlet ubj_{name} : String =\n"
            + "\n".join(f"  #|{ln}" for ln in lines)
            + "\n"
        )
    parts.append(
        "\n///|\nlet ubj_fixtures : Array[(String, Fixture)] = [\n"
        + "".join(f"  (ubj_{n}, fixture_{n}),\n" for n in NAMES)
        + "]\n"
    )
    (ROOT / "ubjson_fixtures_test.mbt").write_text("".join(parts))


if __name__ == "__main__":
    main()
